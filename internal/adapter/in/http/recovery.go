package http

import (
	"context"
	"net/http"

	"github.com/danielgtaylor/huma/v2"
	portin "github.com/rajabinekoo/sigryx/internal/core/port/in"
)

type exportRecoveryOutput struct {
	Body struct {
		RecoveryKey string `json:"recovery_key" doc:"One-time 256-bit recovery key generated by Sigryx. Store it separately from the backup. Sigryx does not persist it."`
		Backup      string `json:"backup" doc:"Opaque encrypted recovery backup. It is cryptographically independent from the current unseal keys and Vault encryption key."`
		KeyRoots    int    `json:"key_roots" doc:"Number of HD key roots included in the backup."`
	}
}

type importRecoveryInput struct {
	Body struct {
		RecoveryKey string `json:"recovery_key" doc:"Recovery key returned by the export operation, including its rec_ prefix."`
		Backup      string `json:"backup" doc:"Opaque backup returned by the export operation."`
	}
}

type importRecoveryOutput struct {
	Body struct {
		KeyRoots int `json:"key_roots" doc:"Number of key roots restored and re-encrypted with the current Vault encryption key."`
	}
}

func registerRecoveryRoutes(api huma.API, recovery portin.RecoveryUseCase) {
	huma.Register(api, huma.Operation{
		OperationID: "export_recovery_backup",
		Method:      http.MethodPost,
		Path:        "/v1/recovery/export",
		Summary:     "Export encrypted key-root recovery backup",
		Description: "Root Admin only. Requires an unsealed Vault. Generates a fresh recovery key, encrypts every HD master seed independently from the current unseal keys, and returns both the opaque backup and recovery key once. Sigryx persists neither value.",
		Tags:        []string{"recovery"},
	}, func(ctx context.Context, _ *emptyInput) (*exportRecoveryOutput, error) {
		principal, ok := principalFromContext(ctx)
		if !ok {
			return nil, huma.Error401Unauthorized("authentication required")
		}

		result, err := recovery.Export(ctx, portin.ExportRecoveryInput{Principal: principal})
		if err != nil {
			return nil, translate(err)
		}

		out := &exportRecoveryOutput{}
		out.Body.RecoveryKey = result.RecoveryKey
		out.Body.Backup = result.Backup
		out.Body.KeyRoots = result.KeyRoots
		return out, nil
	})

	huma.Register(api, huma.Operation{
		OperationID: "import_recovery_backup",
		Method:      http.MethodPost,
		Path:        "/v1/recovery/import",
		Summary:     "Import encrypted key-root recovery backup",
		Description: "Root Admin only. Requires an unsealed Vault. Decrypts the backup with the supplied recovery key and transactionally restores each master seed under the current Vault encryption key. Old unseal keys are not required.",
		Tags:        []string{"recovery"},
	}, func(ctx context.Context, in *importRecoveryInput) (*importRecoveryOutput, error) {
		principal, ok := principalFromContext(ctx)
		if !ok {
			return nil, huma.Error401Unauthorized("authentication required")
		}

		result, err := recovery.Import(ctx, portin.ImportRecoveryInput{
			Principal:   principal,
			RecoveryKey: in.Body.RecoveryKey,
			Backup:      in.Body.Backup,
		})
		if err != nil {
			return nil, translate(err)
		}

		out := &importRecoveryOutput{}
		out.Body.KeyRoots = result.KeyRoots
		return out, nil
	})
}
